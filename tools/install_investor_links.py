#!/usr/bin/env python3
"""Keep the investor-loan section linked from the rest of the WCCM site.

Idempotent and re-applied on every build (see netlify.toml), so a page that a
generator or another workflow rewrites cannot silently drop these links:

1. "Investors" in every primary navigation, right after Loans / Loan Options.
2. A "05 · Investors" card in the homepage "Choose your next step" funnel.
3. An investor-program block on /loans, plus cross-links from /dscr-loans and
   /investment-property-loans to the new short-term investor programs.

The investor pages themselves are generated by tools/build_investor_loan_pages.py.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

PUBLISH_DIR = Path(__file__).resolve().parent.parent / "wccm-corporate"

NAV_RE = re.compile(r'(<nav class="mainnav"[^>]*>)(.*?)(</nav>)', re.IGNORECASE | re.DOTALL)
# Matches the Loans link in every nav variant: loans.html, /loans.html, /loans, ../../loans.html
LOANS_LINK_RE = re.compile(
    r'<a href="(?P<prefix>(?:\.\./)*/?)loans(?P<ext>\.html)?"[^>]*>\s*(?:Loans|Loan Options)\s*</a>',
    re.IGNORECASE,
)
INVESTOR_HREF_RE = re.compile(r'href="(?:\.\./)*/?investor-loans(?:\.html)?"', re.IGNORECASE)

HOME_CARD_MARKER = "<!-- INVESTOR-CARD -->"
HOME_CARD = HOME_CARD_MARKER + """
      <a class="mortgage-funnel-card investor-card" href="investor-loans.html">
        <span class="mortgage-funnel-meta"><b>02</b><b>PRIVATE LENDING</b></span>
        <h2>Investors</h2>
        <p>Private lending for real estate investors: fix &amp; flip, construction, bridge and rental loans, closed in your LLC.</p>
        <span class="mortgage-funnel-action">SEE INVESTOR PROGRAMS <span aria-hidden="true">&rarr;</span></span>
      </a>
      """
HOME_ANCHOR = '<a class="mortgage-funnel-card" href="refinance.html">'

LOANS_BLOCK_START = "<!-- INVESTOR-LOANS:start -->"
LOANS_BLOCK_END = "<!-- INVESTOR-LOANS:end -->"
LOANS_BLOCK = LOANS_BLOCK_START + """
<section class="bg-light"><div class="wrap">
  <div class="section-head"><span class="eyebrow">Real estate investors</span><h2>Investor &amp; business-purpose loans</h2><p class="lead">Short-term financing to buy, renovate, build and hold investment property &mdash; for borrowers who close in an LLC or corporation.</p></div>
  <div class="grid grid-3"><a class="card" href="fix-and-flip-loans.html"><span class="label">Fix &amp; Flip</span><h3>Fix and Flip Loans</h3><p>Up to 90% of purchase and 100% of the rehab budget, interest only.</p><span class="more">Learn more <span aria-hidden="true">&rarr;</span></span></a><a class="card" href="ground-up-construction-loans.html"><span class="label">New Construction</span><h3>Ground-Up Construction Loans</h3><p>Land plus 100% of the construction budget for experienced builders.</p><span class="more">Learn more <span aria-hidden="true">&rarr;</span></span></a><a class="card" href="bridge-loans.html"><span class="label">Bridge</span><h3>Investor Bridge Loans</h3><p>Short-term financing for finished properties that are listed or leasing up.</p><span class="more">Learn more <span aria-hidden="true">&rarr;</span></span></a><a class="card" href="rental-portfolio-loans.html"><span class="label">Portfolio</span><h3>Rental Portfolio Loans</h3><p>Two to ten rentals in one 30-year loan, qualified on rent.</p><span class="more">Learn more <span aria-hidden="true">&rarr;</span></span></a><a class="card" href="multifamily-bridge-loans.html"><span class="label">5+ Units</span><h3>Multifamily Bridge Loans</h3><p>$2M&ndash;$5M to buy and renovate California apartment buildings.</p><span class="more">Learn more <span aria-hidden="true">&rarr;</span></span></a><a class="card" href="investor-loans.html"><span class="label">All programs</span><h3>Compare Investor Loans</h3><p>Side-by-side leverage, loan sizes, terms and credit minimums.</p><span class="more">Compare <span aria-hidden="true">&rarr;</span></span></a></div>
</div></section>
""" + LOANS_BLOCK_END

CROSS_BLOCK_START = "<!-- INVESTOR-CROSSLINKS:start -->"
CROSS_BLOCK_END = "<!-- INVESTOR-CROSSLINKS:end -->"
CROSS_BLOCK = CROSS_BLOCK_START + """
<section><div class="wrap inv-answer">
  <h2>Still needs work before it can be rented?</h2>
  <p>A DSCR loan is for a property that is ready to rent. If it still needs a rehab or is being built, it is usually financed first with a <a href="fix-and-flip-loans.html">fix and flip</a>, <a href="ground-up-construction-loans.html">ground-up construction</a> or <a href="bridge-loans.html">bridge loan</a>, then refinanced into a DSCR loan once it is rented. Have several rentals? See <a href="rental-portfolio-loans.html">rental portfolio loans</a>.</p>
  <div class="btn-row"><a class="btn btn-blue" href="investor-loans.html">See All Investor Loans</a></div>
</div></section>
""" + CROSS_BLOCK_END
CROSS_PAGES = ("dscr-loans.html", "investment-property-loans.html")
CTA_SECTION_RE = re.compile(r'<section><div class="wrap"><div class="cta-band">')


def investor_href(match: re.Match) -> str:
    return f'{match.group("prefix")}investor-loans{match.group("ext") or ""}'


def add_nav_link(text: str, active: bool = False) -> tuple[str, int]:
    """Insert the Investors link after Loans in every primary nav that lacks it."""
    changed = 0

    def fix(nav: re.Match) -> str:
        nonlocal changed
        body = nav.group(2)
        if INVESTOR_HREF_RE.search(body):
            return nav.group(0)
        loans = LOANS_LINK_RE.search(body)
        if not loans:
            return nav.group(0)
        cls = ' class="active"' if active else ""
        link = f'<a href="{investor_href(loans)}"{cls}>Investors</a>'
        changed += 1
        return nav.group(1) + body[: loans.end()] + link + body[loans.end():] + nav.group(3)

    return NAV_RE.sub(fix, text), changed


def add_home_card(text: str) -> tuple[str, bool]:
    if HOME_CARD_MARKER in text or HOME_ANCHOR not in text:
        return text, False
    return text.replace(HOME_ANCHOR, HOME_CARD + HOME_ANCHOR, 1), True


def replace_block(text: str, start: str, end: str, block: str, before: re.Pattern) -> tuple[str, bool]:
    """Install or refresh a marked block, placed before the first `before` match."""
    s, e = text.find(start), text.find(end)
    if s >= 0 and e > s:
        current = text[s:e + len(end)]
        if current == block:
            return text, False
        return text[:s] + block + text[e + len(end):], True
    anchor = before.search(text)
    if not anchor:
        return text, False
    return text[: anchor.start()] + block + "\n" + text[anchor.start():], True


def main(publish: Path = PUBLISH_DIR) -> int:
    if not publish.is_dir():
        raise SystemExit(f"Publish directory not found: {publish}")
    nav_links = pages = 0
    for page in sorted(publish.rglob("*.html")):
        if "graphify-out" in page.parts:
            continue
        text = page.read_text(encoding="utf-8")
        if 'class="mainnav"' not in text:
            continue
        pages += 1
        updated, added = add_nav_link(text)
        if added:
            page.write_text(updated, encoding="utf-8")
            nav_links += added

    home = publish / "index.html"
    text, card = add_home_card(home.read_text(encoding="utf-8"))
    if card:
        home.write_text(text, encoding="utf-8")

    loans = publish / "loans.html"
    text, loans_changed = replace_block(
        loans.read_text(encoding="utf-8"), LOANS_BLOCK_START, LOANS_BLOCK_END, LOANS_BLOCK,
        re.compile(r"<!-- LOCAL-MARKETS:start -->|" + CTA_SECTION_RE.pattern),
    )
    if loans_changed:
        loans.write_text(text, encoding="utf-8")

    cross = 0
    for name in CROSS_PAGES:
        path = publish / name
        text, changed = replace_block(path.read_text(encoding="utf-8"), CROSS_BLOCK_START,
                                      CROSS_BLOCK_END, CROSS_BLOCK, CTA_SECTION_RE)
        if changed:
            path.write_text(text, encoding="utf-8")
            cross += 1

    # Verify instead of trusting the edits: every nav must now link the section.
    missing = []
    for page in sorted(publish.rglob("*.html")):
        if "graphify-out" in page.parts:
            continue
        text = page.read_text(encoding="utf-8")
        for nav in NAV_RE.finditer(text):
            if LOANS_LINK_RE.search(nav.group(2)) and not INVESTOR_HREF_RE.search(nav.group(2)):
                missing.append(str(page.relative_to(publish)))
    if missing:
        raise SystemExit("Investors nav link missing on: " + ", ".join(missing[:10]))
    for name, token in (("index.html", HOME_CARD_MARKER), ("loans.html", LOANS_BLOCK_START),
                        *((n, CROSS_BLOCK_START) for n in CROSS_PAGES)):
        if token not in (publish / name).read_text(encoding="utf-8"):
            raise SystemExit(f"Investor link block missing on {name}")

    print(f"Investor links: nav added {nav_links} across {pages} pages; home card {'added' if card else 'ok'}; "
          f"loans block {'written' if loans_changed else 'ok'}; cross-links written {cross}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
